const featuredNames = [
  'Ember Classic',
  'Oak-Fired Ribeye',
  'Wood-Fired Margherita',
  'Truffle Mushroom Pasta',
];
export const menuItems: MenuItem[] = groups.flatMap((group) =>
  group.items.map(([name, price, description, ingredients, tags = '', spice = 0]) => {
    const slug = name
      .toLowerCase()
      .replace(/&/g, 'and')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
    return {
      id: slug,
      slug,
      name,
      price,
      description,
      category: group.category,
      image: name === 'Smoked BBQ Feast' ? images.feast : group.image,
      ingredients: ingredients.split(', '),
      dietaryTags: tags ? [tags] : [],
      spicyLevel: spice,
      featured: featuredNames.includes(name),
      popular: [
        'Ember Classic',
        'Fire Roasted Wings',
        'Smokehouse BBQ Burger',
        'Chocolate Lava Cake',
      ].includes(name),
    };
  }),
);
export const featuredItems = menuItems.filter((item) => item.featured);
export const money = (value: number) =>
  new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: 2,
  }).format(value);
